// helpText describes everything the bot does, the switched-off scenarios
// left out. Keep it in sync with the scenarios (sales.go, plan.go,
// tasks_schedule.go, quiet.go) and docs/bot.md.
func helpText(f config.Features) string {
	sales, asks := helpSalesPoll, helpPublishAsk
	if !f.SalesPoll {
		sales = ""
	}
	if !f.PublishQuestions {
		asks = "."
	}
	tgAsks := " После поста — «Выложено?», как у остальных."
	if !f.PublishQuestions {
		tgAsks = ""
	}
	mat := helpMaterialReplies
	if !f.MaterialReplies {
		mat = " Один раз, без напоминаний; админа не тегает."
	}
	off := helpOff(f)
	return strings.NewReplacer("{sales}", sales, "{asks}", asks, "{mat}", mat, "{tgasks}", tgAsks, "{off}", off).Replace(helpTemplate)
}

// helpOff lists the switched-off scenarios.
func helpOff(f config.Features) string {
	var off []string
	if !f.SalesPoll {
		off = append(off, "вечерний опрос продажников «отправил?»")
	}
	if !f.PublishQuestions {
		off = append(off, "«Выложено?» после публикации")
	}
	if !f.MaterialReplies {
		off = append(off, "материал ответом на сообщение бота («материал получен»)")
	}
	if len(off) == 0 {
		return ""
	}
	return "<b>Выключено</b> (включается в .env)\n" + strings.Join(off, "; ") + "\n\n"
}

const helpSalesPoll = `<b>Опрос продажников</b> (пн–пт)
18:00 — «@продажник, пришли отчёт за сегодня руководителю в личку»
18:20, 18:40 — «Отправил?» [✅ Да] [❌ Нет] — нажать может только тот, кого тегнули
до 20:40 — ещё можно нажать «Да»; затем итог дня всем админам в личку

`

const helpMaterialReplies = ` Материал — файл или ссылка ответом на сообщение бота. Один раз, без напоминаний; админа не тегает.`

const helpPublishAsk = `; через 30 мин после публикации «Выложено?» [✅ Да] [❌ Нет], до 4 раз.`

const helpTemplate = `❓ <b>Что умеет бот</b>

<b>Команды</b>
/today — сегодня: публикации и материал
/week — неделя с понедельника: что выложено, что впереди, по дням, типам и людям
/month — месяц (пока не готов)
/people — люди: роль и кто в YouGile (чтобы бот отмечал исполнителей); менять может суперадмин, админы смотрят
/admins — админы и 📌 основной (только суперадмин); продажники — в /people
/chats — групповые чаты: 📎 материалы, 🔔 выкладка, 💼 продажи, ✈️ телеграм
/status — версия, база, YouGile, пользователи, групповые чаты
/whoami — твой ID (в группе — ещё и ID чата)
/help — эта справка

<b>Роли</b>
• Новый человек нажимает «Начать» → суперадмину приходит его карточка: роль и кто он в YouGile. То же — в /people.
• Роли — в /people: ⭐ админ, 💼 продажник, ✈️ телеграм (ведёт Telegram-канал). Роль можно дать только тому, кто сам написал боту.
• 📌 Основной админ — его одного бот тегает в чатах и называет продажникам. Первый админ становится основным сам.
• Посторонним бот не отвечает.

<b>Отчёт продажников</b> (в чат продаж с тегом; нет чата — в личку)
пн, ср, пт 16:00 — «пора заполнить отчёт в Яндекс Документах» (с SALES_REPORT_URL — кнопка со ссылкой), без вопросов

{sales}<b>Контент-план</b> (в чат 🔔 выкладки)
пн 13:00 — «заполните контент-план на неделю», админа не тегает

<b>Публикации из YouGile</b> (доска «ПУБЛИКАЦИИ ВСЕГО», сверка раз в 30 мин с 05:00 до 23:00)
• 📎 В чат материалов. Пост, рилс: за сутки (с выходных — в пятницу) «пришли материал».{mat}
• 🔔 В чат выкладки. Сторис, пост, рилс: за 30 мин{asks}
• ✈️ Телеграм: в день с постами — одно сообщение за час до первого, со списком постов дня, в чат ✈️ телеграма (нет его — в чат выкладки); тегает людей с ролью «Телеграм» (нет таких — основного админа).{tgasks}
• Исполнитель из YouGile с тегом, если связан с Telegram в /people; иначе по имени. Нет исполнителя — основной админ.
• В YouGile бот ничего не меняет, только читает.

<b>Тихие часы</b>
22:00–06:00 — по расписанию ничего не отправляется, перенос на 06:00.

<b>Групповые чаты</b>
• Добавить бота в группу можешь ты или админ — тебе придёт вопрос: [📎 Материалы] [🔔 Выкладка] [💼 Продажи]. Поменять — в /chats (тебе и админам).
• Когда чату назначена роль, бот здоровается там с кнопкой «Начать». Повторить для новых людей — /hello@бот в чате (суперадмин или админ).
• Если бота добавил кто-то другой — бот сам выйдет и предупредит тебя.
• Бот запоминает, кого заметил в чатах — см. /status.

{off}<b>Скоро</b>
Отчёт за неделю по воскресеньям в 21:00; Excel за месяц.

Подробно: docs/bot.md и блок-схемы docs/bot-flow.pdf.`

func (t *Bot) onHelp(ctx context.Context, _ *bot.Bot, update *models.Update) {
	t.reply(ctx, update.Message, helpText(t.features))
}
